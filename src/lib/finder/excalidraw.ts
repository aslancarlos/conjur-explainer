export interface ExportLabels {
  title: string
  generatedBy: string          // "Generated by Machine Identity Academy (demo.minha.cloud)"
  selected: string             // "Selected"
  edition: string              // "Edition"
  editionValue: string         // "SaaS" | "Self-Hosted"
  legend: string
  outbound: string
  inbound: string
  internal: string
  external: string
  inferredNote: string         // footnote on inferred flows
}

export const DEFAULT_EXPORT_LABELS: ExportLabels = {
  title: 'Reference architecture',
  generatedBy: 'Generated by Machine Identity Academy (demo.minha.cloud)',
  selected: 'Selected',
  edition: 'Edition',
  editionValue: 'SaaS',
  legend: 'Legend',
  outbound: 'Outbound from customer network',
  inbound: 'Inbound to customer network',
  internal: 'Internal (customer network)',
  external: 'Provider to provider (no customer rule)',
  inferredNote: 'Flows marked "inferred" follow the docs but the port or endpoint is not spelled out there: confirm before opening firewall rules.',
}

export const PRODUCT_COLORS: Record<Product, { stroke: string; bg: string }> = {
  sm: { stroke: '#1d4ed8', bg: '#dbeafe' },
  swa: { stroke: '#0e7490', bg: '#cffafe' },
  cp: { stroke: '#6d28d9', bg: '#ede9fe' },
  shub: { stroke: '#a21caf', bg: '#fae8ff' },
  customer: { stroke: '#475569', bg: '#f1f5f9' },
  external: { stroke: '#334155', bg: '#ffffff' },
}

export const DIRECTION_STYLE: Record<Direction, { stroke: string; style: 'solid' | 'dashed' | 'dotted' }> = {
  outbound: { stroke: '#1d4ed8', style: 'solid' },
  inbound: { stroke: '#dc2626', style: 'solid' },
  internal: { stroke: '#475569', style: 'dashed' },
  external: { stroke: '#94a3b8', style: 'dotted' },
}

