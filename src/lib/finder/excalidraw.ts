const csvCell = (v: string) => (/[",\n;]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v)

export function toCsv(r: Resolved): string {
  const head = ['Source', 'Destination', 'Endpoint', 'Port', 'Protocol', 'Direction', 'Purpose', 'Required for', 'Edition', 'Confidence', 'Note', 'Source doc']
  const rows = r.flows.map(f => [
    nodeById(f.from).label, nodeById(f.to).label, f.endpoint, f.port, f.protocol, f.direction, f.purpose,
    f.requiredFor.filter(t => r.selected.includes(t)).join(' '), f.edition, f.confidence, f.note ?? '', f.source.url,
  ])
  return [head, ...rows].map(row => row.map(csvCell).join(',')).join('\n') + '\n'
}

const md = (s: string) => s.replace(/\|/g, '\\|')

export function toMarkdown(r: Resolved, opts: { title?: string; date?: string; labels?: Partial<ExportLabels>; selectedNames?: string[] } = {}): string {
  const L = { ...DEFAULT_EXPORT_LABELS, ...opts.labels }
  const date = opts.date ?? new Date().toISOString().slice(0, 10)
  const out: string[] = []
  out.push(`# ${opts.title ?? L.title}`, '', `${date} | ${L.edition}: ${L.editionValue} | ${L.generatedBy}`, '')
  out.push('## Environment', '', ...(opts.selectedNames ?? r.selected).map(s => `- ${s}`), '')

  out.push('## Components and requirements', '')
  const byNode = new Map<string, typeof r.requirements>()
  r.requirements.forEach(q => byNode.set(q.node, [...(byNode.get(q.node) ?? []), q]))
  for (const [nid, reqs] of byNode) {
    out.push(`### ${nodeById(nid).label}`, '')
    reqs.forEach(q => out.push(`- [ ] ${q.text} (${q.category}, ${q.confidence}${q.note ? `: ${q.note}` : ''}) [doc](${q.source.url})`))
    out.push('')
  }

  out.push('## Network flows', '', '| Source | Destination | Endpoint | Port | Protocol | Direction | Purpose | Confidence |', '|---|---|---|---|---|---|---|---|')
  r.flows.forEach(f => out.push(`| ${md(nodeById(f.from).label)} | ${md(nodeById(f.to).label)} | \`${md(f.endpoint)}\` | ${f.port} | ${md(f.protocol)} | ${f.direction} | ${md(f.purpose)} | ${f.confidence} |`))
  out.push('')

  out.push('## Consolidated firewall rules', '')
  for (const g of r.firewallRules) {
    out.push(`### ${g.direction.toUpperCase()}: from ${g.sourceLabel}`, '')
    g.rules.forEach(rule => out.push(`- [ ] ${rule.protocol} ${rule.port} to \`${rule.endpoint}\` (${rule.destination}): ${rule.purpose}${rule.confidence === 'inferred' ? ' [inferred]' : ''}`))
    out.push('')
  }

  const inferred = r.flows.filter(f => f.confidence === 'inferred')
  out.push('## Notes', '', `- ${L.inferredNote}`)
  inferred.forEach(f => f.note && out.push(`- ${nodeById(f.from).label} to ${nodeById(f.to).label}: ${f.note}`))
  out.push('')

  const docs = new Map<string, string>()
  r.flows.forEach(f => docs.set(f.source.url, f.source.path))
  r.requirements.forEach(q => docs.set(q.source.url, q.source.path))
  out.push('## Documentation', '', ...[...docs.keys()].sort().map(u => `- ${u}`), '')
  return out.join('\n')
}
