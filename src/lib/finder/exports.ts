/** Flows with the number of the diagram edge they are drawn on, in number order. */
export function numberedFlows(r: Resolved) {
  const { flowNo } = computeLayout(r)
  return r.flows
    .map(f => ({ ...f, no: flowNo[f.id] ?? 0 }))
    .sort((a, b) => (a.no || 1e9) - (b.no || 1e9))
}

