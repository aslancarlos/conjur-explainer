const csvCell = (v: string) => (/[",\n;]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v)

export function toCsv(r: Resolved, opts: { labels?: Partial<ExportLabels> } = {}): string {
  const L = { ...DEFAULT_EXPORT_LABELS, ...opts.labels }
  const head = [L.number, L.source, L.destination, L.endpoint, L.port, L.protocol, L.direction, L.purpose, L.edition, L.confidence, L.notes, L.doc]
  const rows = numberedFlows(r).map(f => [
    f.no ? String(f.no) : '', nodeById(f.from).label, nodeById(f.to).label, f.endpoint, f.port, f.protocol, L.directions[f.direction], f.purpose,
    f.edition === 'both' ? 'SaaS, Self-Hosted' : f.edition === 'saas' ? 'SaaS' : 'Self-Hosted', f.confidence === 'documented' ? L.documented : L.inferred, f.note ?? '', f.source.url,
  ])
  // BOM so spreadsheet apps open accents correctly
  return '﻿' + [head, ...rows].map(row => row.map(csvCell).join(',')).join('\n') + '\n'
}

const md = (s: string) => s.replace(/\|/g, '\\|')

export function toMarkdown(r: Resolved, opts: { title?: string; date?: string; labels?: Partial<ExportLabels>; selectedNames?: string[]; goalNames?: string[] } = {}): string {
  const L = { ...DEFAULT_EXPORT_LABELS, ...opts.labels }
  const date = opts.date ?? new Date().toISOString().slice(0, 10)
  const out: string[] = []
  out.push(`# ${opts.title ?? L.title}`, '', `${date} | ${L.edition}: ${L.editionValue}`, '', `_${L.generatedBy}_`, '')
  out.push(`## ${L.environment}`, '', ...(opts.selectedNames ?? r.selected).map(s => `- ${s}`), '')
  if (opts.goalNames?.length) out.push(`**${L.goals}:** ${opts.goalNames.join(', ')}`, '')

  out.push(`## ${L.components}`, '')
  const byNode = new Map<string, typeof r.requirements>()
  r.requirements.forEach(q => byNode.set(q.node, [...(byNode.get(q.node) ?? []), q]))
  for (const [nid, reqs] of byNode) {
    out.push(`### ${nodeById(nid).label}`, '')
    reqs.forEach(q => out.push(`- [ ] ${q.text}${q.confidence === 'inferred' ? ` (${L.inferred}${q.note ? `: ${q.note}` : ''})` : ''} [${L.doc}](${q.source.url})`))
    out.push('')
  }

  out.push(`## ${L.flows}`, '', L.tableNote, '',
    `| ${L.number} | ${L.source} | ${L.destination} | ${L.endpoint} | ${L.port} | ${L.protocol} | ${L.direction} | ${L.purpose} | ${L.confidence} |`,
    '|---|---|---|---|---|---|---|---|---|')
  numberedFlows(r).forEach(f => out.push(`| ${f.no || ''} | ${md(nodeById(f.from).label)} | ${md(nodeById(f.to).label)} | \`${md(f.endpoint)}\` | ${f.port} | ${md(f.protocol)} | ${L.directions[f.direction]} | ${md(f.purpose)} | ${f.confidence === 'documented' ? L.documented : L.inferred} |`))
  out.push('')

  out.push(`## ${L.rules}`, '')
  for (const g of r.firewallRules) {
    out.push(`### ${L.directions[g.direction]}: ${L.from} ${L.zones?.[g.sourceZone] ?? g.sourceLabel}`, '')
    g.rules.forEach(rule => out.push(`- [ ] ${rule.protocol} ${rule.port} → \`${rule.endpoint}\` (${rule.destination}): ${rule.purpose}${rule.confidence === 'inferred' ? ` [${L.inferred}]` : ''}`))
    out.push('')
  }

  const inferred = r.flows.filter(f => f.confidence === 'inferred' && f.note)
  out.push(`## ${L.notes}`, '', `- ${L.inferredNote}`)
  const seen = new Set<string>()
  inferred.forEach(f => { if (!seen.has(f.note!)) { seen.add(f.note!); out.push(`- ${nodeById(f.from).label} → ${nodeById(f.to).label}: ${f.note}`) } })
  out.push('')

  const docs = new Set<string>()
  r.flows.forEach(f => docs.add(f.source.url))
  r.requirements.forEach(q => docs.add(q.source.url))
  out.push(`## ${L.documentation}`, '', ...[...docs].sort().map(u => `- ${u}`), '')
  return out.join('\n')
}
